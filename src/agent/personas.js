/**
 * ============================================================================
 *  src/agent/personas.js —— 机器人人格（Persona）库
 * ----------------------------------------------------------------------------
 *  为什么单独拆一个文件：
 *    提示词里有两类内容，生命周期完全不同：
 *      1) 内核（语言规范 / 工具清单 / 任务拆解 / ReAct 纪律 / 安全规则）
 *         —— 工具一变就必须同步改，只能存在一份；
 *      2) 人格（称呼 / 口头禅 / 吐槽方式 / 汇报语气）
 *         —— 纯风格，与能力无关，可以随便切换、AB 测试。
 *    如果三份提示词各写一遍，以后每加一个工具就要改三处，漏一处就会出现
 *    “赛博打工人会 drop_item、傲娇大师不会”这种人格间能力不一致的怪事。
 *    所以这里是 CORE（能力内核）+ soul（灵魂）组装：换人格只换魂，能力永远对齐。
 *
 *  切换方式（三种都支持）：
 *    · .env：AGENT_PERSONA=worker | tsundere | chunibyo（默认 worker）
 *    · HTTP：GET /api/agent?message=...&persona=chunibyo（临时切换，方便对比）
 *    · 代码：runAgent(msg, emit, { systemPrompt: getSystemPrompt('tsundere') })
 *
 *  想加新人格：在 PERSONAS 里加一项 { label, soul } 即可，CORE 不用碰。
 * ============================================================================
 */

