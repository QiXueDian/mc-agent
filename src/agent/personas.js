const DEFAULT_PERSONA = 'worker'

/** 人格键是否合法（大小写不敏感） */
function isPersona(key) {
  return Object.prototype.hasOwnProperty.call(PERSONAS, String(key || '').trim().toLowerCase())
}

/**
 * 取一份完整提示词：人格（魂）+ 能力内核。
 * @param {string} [key] worker / tsundere / chunibyo，非法或缺省时回落到默认人格
 * @returns {string}
 */
function getSystemPrompt(key) {
  const name = String(key || process.env.AGENT_PERSONA || DEFAULT_PERSONA)
    .trim()
    .toLowerCase()
  const persona = PERSONAS[name] || PERSONAS[DEFAULT_PERSONA]
  return `${persona.soul}\n\n${CORE}`
}

/**
 * 人格清单，供前端下拉框 / /api/health 使用。
 * 正式字段是 id / name / description；key / label 作为别名保留（老调用方不破）。
 */
function listPersonas() {
  return Object.entries(PERSONAS).map(([id, value]) => ({
    id,
    name: value.label,
    description: value.description || '',
    key: id,
    label: value.label
  }))
}

module.exports = {
  PERSONAS,
  DEFAULT_PERSONA,
  CORE,
  isPersona,
  getSystemPrompt,
  listPersonas
}
